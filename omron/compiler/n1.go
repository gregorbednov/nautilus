// Settings are explicit compiler inputs, not inferred from opaque CXP settings.
type N1ImageSettings struct {
	Options           codec.N1TaskOptions      `json:"options"`
	Memory            codec.N1FBMemorySettings `json:"memory"`
	DefinitionNumbers map[string]int           `json:"definitionNumbers"`
	NextEnable        [7]uint32                `json:"nextEnable"`
}

// N1Image retains an immutable generated file. Diagnostic component offsets
// remain component-relative; Tasks reports image-relative task record offsets.
// Editing diagnostic fields does not rewrite the generated bytes.
type N1Image struct {
	HeaderWords  []uint32         `json:"headerWords"`
	ResourceBody *ResourceBody    `json:"resourceBody"`
	Tasks        []TaskRecordSpan `json:"tasks"`
	report       um.N1Report
	data         []byte
}

func (image *N1Image) Bytes() []byte { return bytes.Clone(image.data) }

func (image *N1Image) Summary() um.N1Report {
	report := image.report
	report.Tasks = append([]um.N1TaskReport(nil), report.Tasks...)
	return report
}

// CompileCXPImage links the qualified nonempty FB prefix and task records into
// a complete N1 file. It uses saved instance placement, not new allocation or
// storage initialization. Full-image scope currently requires zero option
// flags and the observed AC0/64/1536 stack; the lower-level codecs cover wider
// independently qualified settings. No PLC transport is used.
func CompileCXPImage(profile codec.Profile, doc *cxp.Document, resource string, settings N1ImageSettings) (*N1Image, error) {
	if doc == nil {
		return nil, ErrStructure
	}
	if settings.Options != (codec.N1TaskOptions{}) {
		return nil, fmt.Errorf("%w: nonzero full-image options require separate qualification", ErrStructure)
	}
	if settings.Memory.Stack != (codec.N1MemoryStack{Address: "AC0", FirstSize: 64, TotalSize: 1536}) {
		return nil, fmt.Errorf("%w: full-image stack requires explicit AC0/64/1536", ErrStructure)
	}
	if _, err := codec.EncodeN1FBMemory(profile, settings.Memory); err != nil {
		return nil, err
	}
	body, err := CompileCXPResourceBody(profile, doc, resource, settings.DefinitionNumbers, settings.NextEnable)
	if err != nil {
		return nil, err
	}
	// Existing instance checks cover pairwise overlap. Also require every
	// occupied region to lie inside its explicitly configured header bank.
	for _, region := range body.FBPrefix.Instances.Instances.Regions {
		base := settings.Memory.Bases[region.BaseRegister]
		start, err := strconv.Atoi(strings.TrimPrefix(base.Address, region.Area))
		if err != nil || region.StartWord < start || region.EndWord > start+base.Size {
			return nil, fmt.Errorf("%w: %s does not fit configured bank %d", ErrStructure, region.Instance, region.BaseRegister)
		}
	}
	if len(body.Words) > MaxInstructions-330 {
		return nil, ErrSourceLimit
	}
	header, err := codec.EncodeN1Header(profile, settings.Options, codec.N1HeaderLayout{DefinitionWords: len(body.FBPrefix.Definitions.Words), InstanceWords: len(body.FBPrefix.Instances.Words), TaskBlockWords: len(body.TaskBlock.Words)}, &settings.Memory)
	if err != nil {
		return nil, err
	}
	words := append(append(append(make([]uint32, 0, 330+len(body.Words)), header...), body.TaskConfiguration.Words...), body.Words...)
	data := make([]byte, 4*len(words))
	for i, w := range words {
		binary.BigEndian.PutUint32(data[4*i:], w)
	}
	// Independently inspect section extents and record wrappers before exposing
	// the file. This establishes structural consistency, not deployability.
	parsed, err := um.ParseN1(data)
	if err != nil {
		return nil, err
	}
	if _, err := parsed.FunctionBlocks(); err != nil {
		return nil, err
	}
	result := &N1Image{HeaderWords: header, ResourceBody: body, data: data, report: parsed.Summary(), Tasks: make([]TaskRecordSpan, len(body.TaskBlock.Records))}
	for i, record := range body.TaskBlock.Records {
		record.OffsetWords += 330 + body.TaskDirectoryOffsetWords
		result.Tasks[i] = record
	}
	return result, nil
}
